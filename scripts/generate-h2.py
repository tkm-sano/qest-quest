"""Generate the browser's H2/STO-3G two-configuration Hamiltonians.

Requires pyscf==2.14.0 and numpy. Run from any working directory.
The 1-qubit encoding is |0>=doubly occupied bonding MO, |1>=doubly
occupied antibonding MO. Verify its ground energy against full CI.
"""
import json
from pathlib import Path
import numpy as np
import pyscf
from pyscf import gto, scf, ao2mo, fci

records = []
for distance in [0.4, 0.735, 1.0, 1.5, 2.0]:
    molecule = gto.M(atom=f"H 0 0 0; H 0 0 {distance}", basis="sto-3g", unit="Angstrom", verbose=0)
    mean_field = scf.RHF(molecule).run(conv_tol=1e-12)
    assert mean_field.converged
    orbitals = mean_field.mo_coeff
    h1 = orbitals.T @ mean_field.get_hcore() @ orbitals
    eri = ao2mo.kernel(molecule, orbitals)
    addresses, matrix = fci.direct_spin1.pspace(h1, eri, 2, (1, 1), np=4)
    positions = [list(addresses).index(address) for address in [0, 3]]
    reduced = matrix[np.ix_(positions, positions)]
    nuclear = molecule.energy_nuc()
    exact, _ = fci.direct_spin1.kernel(h1, eri, 2, (1, 1), tol=1e-12)
    ground = float(np.linalg.eigvalsh(reduced)[0] + nuclear)
    assert abs(ground - exact - nuclear) < 1e-9
    records.append(dict(distance=distance, identity=float(np.trace(reduced) / 2 + nuclear),
                        z=float((reduced[0, 0] - reduced[1, 1]) / 2), x=float(reduced[0, 1]),
                        ground=ground, hartreeFock=float(mean_field.e_tot)))

output = Path(__file__).resolve().parents[1] / "js/quantum/h2-data.js"
output.write_text("// Generated by scripts/generate-h2.py; PySCF " + pyscf.__version__ +
                  "; STO-3G; Angstrom; total energies in Hartree (nuclear repulsion included).\n" +
                  "export const H2_MOLECULES = " + json.dumps(records, indent=2) + ";\n")
print(output)
